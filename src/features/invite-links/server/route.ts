import { Hono } from "hono";
import { z } from "zod";
import { zValidator } from "@hono/zod-validator";
import { sessionMiddleware } from "@/lib/session-middleware";
import { ID, Query, getAdminDatabases } from "@/lib/supabase";
import {
  DATABASE_ID,
  MEMBERS_ID,
  ROLES_ID,
  INVITE_LINKS_ID,
  WORKSPACES_ID,
  ACADEMIC_TEAMS_ID,
  BATCHES_ID,
  TEAM_GUIDES_ID,
  ACADEMIC_TEAM_MEMBERS_ID,
  CHANNELS_ID,
  CHANNEL_MEMBERS_ID,
} from "@/config";
import { getMemberPermissionProfile } from "@/lib/permissions/server";
import { can } from "@/lib/permissions/engine";
import type { InviteLink } from "@/features/access-requests/types";
import { Workspace } from "@/features/workspaces/types";
import { Member, MemberRole } from "@/features/members/types";

const app = new Hono()
  // ── LIST ────────────────────────────────────────────────────────────────
  .get(
    "/",
    sessionMiddleware,
    zValidator("query", z.object({ workspaceId: z.string() })),
    async (c) => {
      const user = c.get("user");
      const databases = c.get("databases");
      const { workspaceId } = c.req.valid("query");

      const profile = await getMemberPermissionProfile(databases, workspaceId, user.$id);
      if (!profile) return c.json({ error: "Unauthorized" }, 401);
      if (!can(profile, "invites:manage")) {
        return c.json({ error: "Forbidden", requiredPermission: "invites:manage", canRequest: true }, 403);
      }

      const links = await databases.listDocuments<InviteLink>(
        DATABASE_ID, INVITE_LINKS_ID,
        [Query.equal("workspaceId", workspaceId), Query.orderDesc("created_at")]
      );

      return c.json({ data: links });
    }
  )
  // ── CREATE ──────────────────────────────────────────────────────────────
  .post(
    "/",
    sessionMiddleware,
    zValidator(
      "json",
      z.object({
        workspaceId: z.string(),
        roleId: z.string().optional(),
        target_role: z
          .enum([
            "FACULTY_GUIDE",
            "STUDENT_LEAD",
            "STUDENT",
            "MEMBER",
            "ADMIN",
            "VIEWER",
          ])
          .optional(),
        academic_team_id: z.string().optional(),
        batch_id: z.string().optional(),
        label: z.string().max(80).optional(),
        expiresAt: z.string().datetime().optional(),
        maxUses: z.number().int().positive().optional(),
      })
    ),
    async (c) => {
      const user = c.get("user");
      const databases = c.get("databases");
      const {
        workspaceId,
        roleId,
        target_role,
        academic_team_id,
        batch_id,
        label,
        expiresAt,
        maxUses,
      } = c.req.valid("json");

      const profile = await getMemberPermissionProfile(databases, workspaceId, user.$id);
      if (!profile) return c.json({ error: "Unauthorized" }, 401);

      const isOwner =
        profile.isWorkspaceOwner === true ||
        (profile.role.isSystem && profile.role.level === 0);
      const isHod = isOwner || profile.role.level <= 10;

      // Hierarchical Permission Gates
      if (target_role === "FACULTY_GUIDE") {
        if (!isHod && !can(profile, "college:batches.manage") && !can(profile, "invites:manage")) {
          return c.json({ error: "Only HOD/Department Admins can generate Faculty Guide invite codes" }, 403);
        }
      } else if (target_role === "STUDENT" || target_role === "STUDENT_LEAD") {
        // Can be generated by HOD, Faculty Guide, or Student Team Lead
        const canManageGroups =
          isHod ||
          can(profile, "college:groups.manage") ||
          can(profile, "college:groups.lead") ||
          can(profile, "invites:manage");

        if (!canManageGroups) {
          return c.json({ error: "Permission denied to generate Student Group invite codes" }, 403);
        }
      } else if (!can(profile, "invites:manage")) {
        return c.json({ error: "Forbidden", requiredPermission: "invites:manage", canRequest: true }, 403);
      }

      // Anti-escalation: cannot create invite link for a role at or above actor's own level (unless owner)
      if (!isOwner && roleId) {
        try {
          const targetRole = await databases.getDocument<{ level: number }>(DATABASE_ID, ROLES_ID, roleId);
          if (targetRole.level <= profile.role.level) {
            return c.json({ error: "Cannot create invite link for a role at or above your own level" }, 403);
          }
        } catch { /* role not found */ }
      }

      const code = Math.random().toString(36).slice(2, 12).toUpperCase();

      const link = await databases.createDocument<InviteLink>(
        DATABASE_ID, INVITE_LINKS_ID, ID.unique(),
        {
          workspaceId,
          roleId: roleId || null,
          target_role: target_role || null,
          academic_team_id: academic_team_id || null,
          batch_id: batch_id || null,
          created_by_member_id: profile.id,
          code,
          label: label || null,
          expiresAt: expiresAt || null,
          maxUses: maxUses || null,
          uses: 0,
          createdBy: profile.id,
          revoked: false,
        }
      );

      return c.json({ data: link }, 201);
    }
  )
  // ── REVOKE ───────────────────────────────────────────────────────────────
  .delete(
    "/:linkId",
    sessionMiddleware,
    zValidator("json", z.object({ workspaceId: z.string() })),
    async (c) => {
      const user = c.get("user");
      const databases = c.get("databases");
      const { linkId } = c.req.param();
      const { workspaceId } = c.req.valid("json");

      const profile = await getMemberPermissionProfile(databases, workspaceId, user.$id);
      if (!profile) return c.json({ error: "Unauthorized" }, 401);
      if (!can(profile, "invites:manage")) {
        return c.json({ error: "Forbidden", requiredPermission: "invites:manage", canRequest: true }, 403);
      }

      await databases.updateDocument(DATABASE_ID, INVITE_LINKS_ID, linkId, { revoked: true });
      return c.json({ data: { id: linkId, revoked: true } });
    }
  )
  // ── LOOKUP (public — used by join preview) ────────────────────────────────
  .get(
    "/lookup",
    sessionMiddleware,
    zValidator("query", z.object({ code: z.string() })),
    async (c) => {
      const { code } = c.req.valid("query");
      const adminDatabases = getAdminDatabases("invite-links:lookup");

      try {
        const links = await adminDatabases.listDocuments<InviteLink & { workspaceId: string }>(
          DATABASE_ID, INVITE_LINKS_ID,
          [Query.equal("code", code.trim().toUpperCase()), Query.limit(1)]
        );

        if (links.total === 0) return c.json({ error: "Invalid or expired invite link" }, 404);
        const link = links.documents[0];

        if (link.revoked) return c.json({ error: "This invite link has been revoked" }, 410);
        if (link.expiresAt && new Date(link.expiresAt) < new Date()) {
          return c.json({ error: "This invite link has expired" }, 410);
        }
        if (link.maxUses && link.uses >= link.maxUses) {
          return c.json({ error: "This invite link has reached its maximum uses" }, 410);
        }

        const workspace = await adminDatabases.getDocument<Workspace>(DATABASE_ID, WORKSPACES_ID, link.workspaceId);

        let roleName: string | undefined;
        let previewBadgeText: string | undefined;
        let teamCode: string | undefined;
        let teamTitle: string | undefined;
        let guideName: string | undefined;
        let batchName: string | undefined;

        if (link.academic_team_id) {
          try {
            const team = await adminDatabases.getDocument<{
              id: string;
              team_code: string;
              title: string;
              batch_id: string;
            }>(DATABASE_ID, ACADEMIC_TEAMS_ID, link.academic_team_id);

            teamCode = team.team_code;
            teamTitle = team.title;

            // Fetch Guide info
            const guides = await adminDatabases.listDocuments<{ guide_member_id: string }>(
              DATABASE_ID,
              TEAM_GUIDES_ID,
              [Query.equal("team_id", team.id), Query.limit(1)]
            );

            if (guides.total > 0) {
              const guideMember = await adminDatabases.getDocument<{ name?: string; email?: string }>(
                DATABASE_ID,
                MEMBERS_ID,
                guides.documents[0].guide_member_id
              ).catch(() => null);
              guideName = guideMember?.name || guideMember?.email || "Faculty Guide";
            }

            // Fetch Batch info
            if (team.batch_id) {
              const batch = await adminDatabases.getDocument<{ name: string }>(
                DATABASE_ID,
                BATCHES_ID,
                team.batch_id
              ).catch(() => null);
              batchName = batch?.name;
            }
          } catch {
            // Team fetch failed
          }
        }

        if (link.target_role === "FACULTY_GUIDE") {
          roleName = "Faculty Guide";
          previewBadgeText = `You are joining as Faculty Guide under ${workspace.name}`;
        } else if (link.target_role === "STUDENT_LEAD") {
          roleName = "Student Team Lead";
          previewBadgeText = `You are joining as Team Lead for ${teamCode ? `${teamCode} - ${teamTitle}` : "Project Group"}${guideName ? ` (Guide: ${guideName})` : ""}`;
        } else if (link.target_role === "STUDENT" || link.academic_team_id) {
          roleName = "Student Member";
          previewBadgeText = `You are joining ${teamCode ? `${teamCode} - ${teamTitle}` : "Academic Project Group"}${guideName ? ` (Guide: ${guideName})` : ""}`;
        } else if (link.roleId) {
          const role = await adminDatabases.getDocument<{ name: string }>(DATABASE_ID, ROLES_ID, link.roleId).catch(() => null);
          roleName = role?.name;
          previewBadgeText = `Assigned Role: ${roleName || "Member"}`;
        }

        return c.json({
          data: {
            workspaceId: link.workspaceId,
            workspaceName: workspace.name,
            workspaceImageUrl: workspace.imageUrl,
            roleId: link.roleId,
            roleName: roleName || "Member (View Only)",
            targetRole: link.target_role || null,
            academicTeamId: link.academic_team_id || null,
            teamCode: teamCode || null,
            teamTitle: teamTitle || null,
            guideName: guideName || null,
            batchName: batchName || null,
            previewBadgeText: previewBadgeText || null,
            code: link.code,
            linkId: link.id || link.$id,
          },
        });
      } catch {
        return c.json({ error: "Invalid invite link" }, 404);
      }
    }
  )
  // ── JOIN via invite link (Atomic use increment) ──────────────────────────
  .post(
    "/join",
    sessionMiddleware,
    zValidator("json", z.object({ code: z.string() })),
    async (c) => {
      const user = c.get("user");
      const userDatabases = c.get("databases");
      const { code } = c.req.valid("json");
      const adminDatabases = getAdminDatabases("invite-links:join");
      const normalizedCode = code.trim().toUpperCase();

      // 1. Try atomic PostgreSQL RPC function first
      try {
        const rpcResult = await adminDatabases.rpc<
          Array<{
            success: boolean;
            workspace_id: string;
            member_id: string;
            target_role: string | null;
            academic_team_id: string | null;
            error_message: string | null;
          }>
        >("accept_workspace_invite_code", {
          p_code: normalizedCode,
          p_user_id: user.$id,
        });

        if (Array.isArray(rpcResult) && rpcResult.length > 0) {
          const res = rpcResult[0];
          if (res.success) {
            return c.json({
              data: {
                workspaceId: res.workspace_id,
                memberId: res.member_id,
                targetRole: res.target_role,
                academicTeamId: res.academic_team_id,
              },
            });
          } else {
            return c.json({ error: res.error_message || "Failed to join via invite code" }, 400);
          }
        }
      } catch {
        // Fallback to JS join flow if RPC is not deployed yet
      }

      // 2. JavaScript fallback transaction
      const links = await adminDatabases.listDocuments<InviteLink & { workspaceId: string; roleId?: string; target_role?: string; academic_team_id?: string }>(
        DATABASE_ID, INVITE_LINKS_ID,
        [Query.equal("code", normalizedCode), Query.limit(1)]
      );

      if (links.total === 0) return c.json({ error: "Invalid invite link" }, 404);
      const link = links.documents[0];
      const linkId = link.id || (link as unknown as { $id?: string }).$id || "";

      if (link.revoked) return c.json({ error: "This invite link has been revoked" }, 410);
      if (link.expiresAt && new Date(link.expiresAt) < new Date()) {
        return c.json({ error: "This invite link has expired" }, 410);
      }
      if (link.maxUses && link.uses >= link.maxUses) {
        return c.json({ error: "This invite link has reached its maximum uses" }, 410);
      }

      const { workspaceId } = link;

      // Reject if already a member of this workspace
      const existing = await adminDatabases.listDocuments<Member>(
        DATABASE_ID, MEMBERS_ID,
        [Query.equal("workspaceId", workspaceId), Query.equal("userId", user.$id), Query.limit(1)]
      );
      if (existing.total > 0) return c.json({ error: "Already a member of this workspace" }, 400);

      // Atomic use consumption: UPDATE ... WHERE uses < maxUses AND revoked = false RETURNING
      let consumed = false;
      try {
        const rpcRows = await adminDatabases.rpc<Array<InviteLink>>(
          "consume_invite_link_use",
          { p_code: normalizedCode }
        );
        if (Array.isArray(rpcRows) && rpcRows.length > 0) {
          consumed = true;
        }
      } catch {
        // Fallback atomic check & update
        const fresh = await adminDatabases.getDocument<InviteLink>(DATABASE_ID, INVITE_LINKS_ID, linkId);
        if (!fresh.revoked && (!fresh.maxUses || fresh.uses < fresh.maxUses) && (!fresh.expiresAt || new Date(fresh.expiresAt) > new Date())) {
          await adminDatabases.updateDocument(DATABASE_ID, INVITE_LINKS_ID, linkId, {
            uses: fresh.uses + 1,
          });
          consumed = true;
        }
      }

      if (!consumed) {
        return c.json({ error: "This invite link has reached its maximum uses or has expired" }, 410);
      }

      // Create member record
      const assignedRole: MemberRole = MemberRole.MEMBER;

      const member = await userDatabases.createDocument<Member>(
        DATABASE_ID, MEMBERS_ID, ID.unique(),
        {
          workspaceId,
          userId: user.$id,
          role: assignedRole,
          roleId: link.roleId || null,
        }
      );

      const memberId = member.$id || member.id;

      // If team-scoped, add to academic_team_members
      if (link.academic_team_id) {
        try {
          await adminDatabases.createDocument(
            DATABASE_ID,
            ACADEMIC_TEAM_MEMBERS_ID,
            ID.unique(),
            {
              team_id: link.academic_team_id,
              member_id: memberId,
              role: link.target_role === "STUDENT_LEAD" ? "LEAD" : "MEMBER",
              joined_at: new Date().toISOString(),
            }
          );
        } catch {
          // Ignore unique conflict
        }

        // Auto-join team's dedicated discussion channel
        try {
          const teamChannels = await adminDatabases.listDocuments<{ id: string }>(
            DATABASE_ID,
            CHANNELS_ID,
            [Query.equal("team_id", link.academic_team_id), Query.limit(1)]
          );
          if (teamChannels.total > 0) {
            await adminDatabases.createDocument(
              DATABASE_ID,
              CHANNEL_MEMBERS_ID,
              ID.unique(),
              {
                channel_id: teamChannels.documents[0].id,
                member_id: user.$id,
                role: link.target_role === "STUDENT_LEAD" ? "MODERATOR" : "MEMBER",
                joined_at: new Date().toISOString(),
              }
            );
          }
        } catch {
          // Channel join error ignored
        }
      }

      return c.json({
        data: {
          workspaceId,
          memberId,
          role: assignedRole,
          roleId: link.roleId || null,
          targetRole: link.target_role || null,
          academicTeamId: link.academic_team_id || null,
        },
      });
    }
  );

export default app;
